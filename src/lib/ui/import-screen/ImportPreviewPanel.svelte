<script lang="ts">
	import type { Placement } from '#lib/db/schemas/common.ts';
	import type { NoteType } from '#lib/db/schemas/note.ts';
	import type { ImportPreview, TopicPreview } from '#lib/services/import-service.ts';

	interface Props {
		preview: ImportPreview;
		placements: ReadonlyMap<string, Placement>;
		onPlacement: (topicName: string, placement: Placement) => void;
		onJumpToLine: (line: number) => void;
	}

	let { preview, placements, onPlacement, onJumpToLine }: Props = $props();

	const NOTE_LABELS: Record<NoteType, string> = {
		keyterm: 'Key terms',
		fact: 'Facts',
		cloze: 'Fill-in sentences',
		sequence: 'Sequences',
		example: 'Worked examples',
		compare: 'Comparison tables',
		scenario: 'Scenarios',
		diagram: 'Diagrams',
		occlusion: 'Image cards'
	};

	const noteTypes = Object.keys(NOTE_LABELS) as NoteType[];

	function placementOf(topic: TopicPreview): Placement {
		return placements.get(topic.name) ?? topic.existing?.placement ?? 'unread';
	}
</script>

<section aria-label="Preview">
	<h2>Preview</h2>

	{#if preview.errors.length > 0}
		<h3>{preview.errors.length} to fix</h3>
		<p>These lines will be left out. Everything else can still be added.</p>
		<ul class="plain">
			{#each preview.errors as error (`${error.line}:${error.message}`)}
				<li>
					<button type="button" onclick={() => onJumpToLine(error.line)}>
						Line {error.line}: {error.message}
					</button>
				</li>
			{/each}
		</ul>
	{/if}

	<h3>What will be added</h3>
	<p>
		{preview.cardCount}
		{preview.cardCount === 1 ? 'card' : 'cards'} from these notes, plus {preview.chunkCount} reading
		{preview.chunkCount === 1 ? 'chunk' : 'chunks'}.
	</p>
	<ul>
		{#each noteTypes as type (type)}
			{#if preview.noteCounts[type]}
				<li>{NOTE_LABELS[type]}: {preview.noteCounts[type]}</li>
			{/if}
		{/each}
	</ul>
	{#if preview.generatedChunkCount > 0}
		<p>
			{preview.generatedChunkCount} reading
			{preview.generatedChunkCount === 1 ? 'chunk was' : 'chunks were'} generated by the chatbot, not
			taken from your notes. Check them against your course.
		</p>
	{/if}

	{#if preview.topics.length > 0}
		<h3>Have you read these topics?</h3>
		<ul class="plain">
			{#each preview.topics as topic (topic.name)}
				<li class="topic">
					<strong>{topic.name}</strong>
					<span>
						{topic.existing ? 'Adds to this topic: ' : ''}{topic.notes} notes, {topic.cards} cards
					</span>
					<span class="taps" role="group" aria-label="Placement for {topic.name}">
						<button
							type="button"
							aria-pressed={placementOf(topic) === 'unread'}
							onclick={() => onPlacement(topic.name, 'unread')}
						>
							Haven't read
						</button>
						<button
							type="button"
							aria-pressed={placementOf(topic) === 'read'}
							onclick={() => onPlacement(topic.name, 'read')}
						>
							Read it
						</button>
					</span>
				</li>
			{/each}
		</ul>
	{/if}

	{#if preview.checked.length > 0}
		<h3>Marked to check</h3>
		<ul class="plain">
			{#each preview.checked as item (item.line)}
				<li>
					<button type="button" onclick={() => onJumpToLine(item.line)}>
						Line {item.line}: {item.text}
					</button>
				</li>
			{/each}
		</ul>
	{/if}

	{#if preview.plan.coverage.length > 0}
		<h3>Sections the chatbot covered</h3>
		<ul>
			{#each preview.plan.coverage as section, index (`${index}:${section}`)}
				<li>{section}</li>
			{/each}
		</ul>
	{/if}

	{#if preview.unusedImages.length > 0}
		<p>Not used by any block, so not saved: {preview.unusedImages.join(', ')}.</p>
	{/if}
</section>

